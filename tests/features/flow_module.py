import sys, os; sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__)))); os.chdir(os.path.dirname(os.path.dirname(os.path.abspath(__file__)))+"/out")
from h18 import *
"""Ynmo Flow, phase 1: menu, create tickets (all types and the parent rules), list, filters, My work, ticket window, status change, history, delete, reload. Fake test database only."""
R=[]
def ok(n,c): R.append((n,bool(c))); print(('PASS ' if c else 'FAIL ')+n)
with sync_playwright() as pw:
    b=pw.chromium.launch(); ctx=mkctx(b); errs=[]
    A=newpage(ctx,errs); signup(A,'Admin','adm@x.com')
    nb=A.locator('#nav button[data-p="flow"]')
    ok('F1 the menu has a Ynmo Flow button with an icon', nb.count()==1 and nb.get_attribute('aria-label')=='Ynmo Flow' and nb.locator('svg').count()==1)
    nb.click(); A.wait_for_timeout(500)
    ok('F2 it opens the Flow page with the title', A.locator('#pg-flow h1').inner_text()=='Ynmo Flow' and A.locator('#ptitle').inner_text()=='Ynmo Flow')
    ok('F3 empty state invites the first ticket and Create is enabled', 'No tickets yet' in A.locator('#flowbody').inner_text() and A.locator('#flowcreate').is_enabled())
    ok('F4 the address shows #/flow and the button is current', A.evaluate("location.hash")=='#/flow' and nb.get_attribute('aria-current')=='page')
    def create(typ,title,asg='',par='',ep='',desc=''):
        A.click('#flowcreate'); A.wait_for_timeout(200)
        A.select_option('#fc-type',typ)
        if par: A.select_option('#fc-par',label=par)
        if ep: A.select_option('#fc-ep',label=ep)
        A.fill('#fc-title',title)
        if desc: A.fill('#fc-desc',desc)
        if asg: A.select_option('#fc-as',asg)
        A.click('#fc-ok'); A.wait_for_timeout(300)
    create('epic','Payments')
    ok('F5 the first ticket is YNMO-1 and shows in the list', A.locator('.flowrow').count()==1 and A.locator('.flowrow .fkey').first.inner_text()=='YNMO-1')
    create('story','Pay by card',asg='Admin',ep='YNMO-1 Payments',desc='Card form and receipt')
    create('bug','Totals are wrong',asg='Admin')
    create('hotfix','Receipt typo')
    ok('F6 four tickets, newest first', A.locator('.flowrow').count()==4 and A.locator('.flowrow .fkey').first.inner_text()=='YNMO-4')
    A.click('#flowcreate'); A.wait_for_timeout(200); A.select_option('#fc-type','subtask'); A.fill('#fc-title','Form'); A.click('#fc-ok'); A.wait_for_timeout(200)
    ok('F7 a sub-task without a parent is refused with a message and the window stays', A.locator('#fc-err').is_visible() and 'parent' in A.locator('#fc-err').inner_text() and A.locator('#fc-title').count()==1)
    A.select_option('#fc-type','story'); A.wait_for_timeout(100)
    ok('F8 parent field is hidden for a story and the epic field is shown', not A.locator('#fc-par').is_visible() and A.locator('#fc-ep').is_visible())
    A.select_option('#fc-type','epic'); A.wait_for_timeout(100)
    ok('F9 an epic has neither parent nor epic', not A.locator('#fc-par').is_visible() and not A.locator('#fc-ep').is_visible())
    A.click('button:text-is("Cancel")'); A.wait_for_timeout(200)
    # open the story and add sub-tasks
    A.locator('.flowrow',has_text='Pay by card').click(); A.wait_for_timeout(300)
    ok('F10 the ticket window shows key, fields and the description', A.locator('#fi-title').input_value()=='Pay by card' and A.locator('#fi-desc').input_value()=='Card form and receipt' and A.locator('#fi-as').input_value()=='Admin')
    ok('F11 a story offers both Add sub-task and Add sub-bug', A.locator('[data-add="subtask"]').count()==1 and A.locator('[data-add="subbug"]').count()==1)
    A.click('[data-add="subtask"]'); A.wait_for_timeout(250)
    ok('F12 the sub-ticket window is preset to Sub-task under the story', A.locator('#fc-type').input_value()=='subtask' and A.locator('#fc-par').input_value()!='')
    A.fill('#fc-title','Card form'); A.select_option('#fc-as','Admin'); A.click('#fc-ok'); A.wait_for_timeout(300)
    A.locator('.flowrow',has_text='Pay by card').click(); A.wait_for_timeout(300)
    A.click('[data-add="subbug"]'); A.wait_for_timeout(250); A.fill('#fc-title','Card form crashes'); A.click('#fc-ok'); A.wait_for_timeout(300)
    A.locator('.flowrow',has_text='Pay by card').click(); A.wait_for_timeout(300)
    ok('F13 the story lists its two sub-tickets', A.locator('.flowkid').count()==2)
    # change status and save
    A.select_option('#fi-st','progress'); A.click('#fi-save'); A.wait_for_timeout(300)
    ok('F14 the status change shows in the list', A.locator('.flowrow',has_text='Pay by card').locator('td').nth(3).inner_text()=='In progress')
    A.locator('.flowrow',has_text='Pay by card').click(); A.wait_for_timeout(300)
    ok('F15 history lists the creation and the status change', 'Open → In progress' in A.locator('.flowhist').inner_text() and 'created YNMO-2' in A.locator('.flowhist').inner_text())
    A.click('button:text-is("Close")'); A.wait_for_timeout(200)
    # filters
    A.fill('#flowq','typo'); A.wait_for_timeout(200)
    ok('F16 text search narrows the list', A.locator('.flowrow').count()==1 and 'Receipt typo' in A.locator('.flowrow').inner_text())
    A.fill('#flowq',''); A.select_option('#flowtype','bug'); A.wait_for_timeout(200)
    ok('F17 type filter', A.locator('.flowrow').count()==1 and 'Totals' in A.locator('.flowrow').inner_text())
    A.select_option('#flowtype',''); A.select_option('#flowas','@none'); A.wait_for_timeout(200)
    ok('F18 unassigned filter', A.locator('.flowrow').count()==3)
    A.select_option('#flowas',''); A.select_option('#flowep',index=1); A.wait_for_timeout(200)
    ok('F19 epic filter shows the tickets of the epic', A.locator('.flowrow').count()==1 and 'Pay by card' in A.locator('.flowrow').inner_text())
    A.select_option('#flowep',''); A.click('.flowchips [data-st="progress"]'); A.wait_for_timeout(300)
    ok('F20 clicking a status chip filters by it and clicking again clears it', A.locator('.flowrow').count()==1 and A.locator('.flowchips [data-st="progress"]').get_attribute('aria-pressed')=='true')
    A.click('.flowchips [data-st="progress"]'); A.wait_for_timeout(300)
    ok('F21 filters cleared', A.locator('.flowrow').count()==6)
    # my work
    A.click('.flowtabs [data-tab="mine"]'); A.wait_for_timeout(300)
    ok('F22 My work: assigned ticket, sub-task and bug sit in their own sections', A.locator('#mine-tickets .flowrow').count()==1 and A.locator('#mine-subs .flowrow').count()==1 and A.locator('#mine-bugs .flowrow').count()==1)
    # done hides, all shows
    A.locator('#mine-bugs .flowrow').click(); A.wait_for_timeout(300); A.select_option('#fi-st','done'); A.click('#fi-save'); A.wait_for_timeout(300)
    ok('F23 a Done ticket leaves My work', A.locator('#mine-bugs .flowrow').count()==0)
    A.check('#flowall'); A.wait_for_timeout(300)
    ok('F24 Include Deployed and Done brings it back', A.locator('#mine-bugs .flowrow').count()==1)
    # reload persists
    A.reload(); A.wait_for_timeout(3500)
    ok('F25 a reload stays on Flow and the tickets are still there (the Done one is hidden by default)', A.locator('#pg-flow:not([hidden])').count()==1 and A.locator('.flowrow').count()==5)
    # delete
    A.locator('.flowrow',has_text='Receipt typo').click(); A.wait_for_timeout(300); A.click('#fi-del'); A.wait_for_timeout(200); A.click('button:text-is("Delete")'); A.wait_for_timeout(400)
    ok('F26 delete removes the ticket after a confirm', A.locator('.flowrow').count()==4 and 'Receipt typo' not in A.locator('#flowbody').inner_text())
    ok('F27 no script errors', not errs)
    if errs: print(errs)
    b.close()
bad=[n for n,c in R if not c]; print('TOTAL',len(R),'PASS',len(R)-len(bad),'FAIL',len(bad)); sys.exit(1 if bad else 0)
