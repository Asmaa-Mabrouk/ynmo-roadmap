import { compare, roadVals } from '../src/esm/features/feature-link.js';
const ok = (n, c) => console.log((c ? 'PASS ' : 'FAIL ') + n);
const road = (t, pc) => roadVals({ t, pc });
let r = compare({ t: 'A', pct: 20 }, { t: 'A', pct: 20 }, road('A', 20));
ok('nothing changed: nothing to do', !r.incoming.length && !r.outgoing.length && !Object.keys(r.rebase).length);
r = compare({ t: 'A', pct: 20 }, { t: 'A', pct: 20 }, road('A2', 60));
ok('roadmap changed, item untouched: both fields are incoming', r.incoming.length === 2 && !r.outgoing.length && r.incoming[0].to === 'A2' && r.incoming[1].to === 60);
r = compare({ t: 'B', pct: 50 }, { t: 'A', pct: 20 }, road('A', 20));
ok('item changed, roadmap untouched: both are outgoing (need an admin)', r.outgoing.length === 2 && !r.incoming.length && r.outgoing[0].road === 'A');
r = compare({ t: 'B', pct: 20 }, { t: 'A', pct: 20 }, road('C', 20));
ok('both changed the title: it is outgoing, with the roadmap value shown', r.outgoing.length === 1 && r.outgoing[0].f === 't' && r.outgoing[0].road === 'C' && r.outgoing[0].to === 'B');
r = compare({ t: 'B', pct: 20 }, { t: 'A', pct: 20 }, road('B', 20));
ok('item and roadmap already agree: nothing to do, the record is refreshed', !r.incoming.length && !r.outgoing.length && r.rebase.t === 'B');
r = compare({ t: 'A', pct: 30 }, { t: 'A', pct: 30 }, road('A', undefined));
ok('no progress on the bar yet: progress is left alone', !r.incoming.length && !r.outgoing.length);
r = compare({ t: 'A', pct: 40 }, { t: 'A', pct: 30 }, road('A', undefined));
ok('a progress change while the bar has none is a request', r.outgoing.length === 1 && r.outgoing[0].f === 'pct' && r.outgoing[0].road === undefined);
r = compare({ t: 'A  x', pct: 0 }, null, road('A x', 0));
ok('no record yet: the item adopts the roadmap; spaces do not count as a change', !r.incoming.length && !r.outgoing.length);
r = compare({ t: 'Old', pct: 0 }, null, road('New', 10));
ok('no record yet and the values differ: they come from the roadmap (incoming)', r.incoming.length === 2 && !r.outgoing.length);
